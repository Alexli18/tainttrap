"""Vendor the Public Suffix List (MPL-2.0) into src/tainttrap/data/psl/suffixes.txt.

Usage: python scripts/vendor_psl.py public_suffix_list.dat --commit SHA

Download the file from https://github.com/publicsuffix/list at a pinned commit. Comments and
blank lines are dropped, and internationalised rules are kept in both forms. ICANN and private
sections are both kept (private suffixes such as github.io matter: anyone can own a subdomain
there). The file is read at runtime with no network access.
"""

from __future__ import annotations

import argparse
import hashlib
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "src/tainttrap/data/psl/suffixes.txt"
NOTICES = ROOT / "THIRD_PARTY_NOTICES"
HEADER = "== Public Suffix List (https://publicsuffix.org) =="


def _puny(label: str) -> str:
    prefix = "!" if label.startswith("!") else ""
    label = label.removeprefix("!")
    if label.isascii():
        return prefix + label
    return prefix + "xn--" + label.encode("punycode").decode()


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("source", type=Path)
    ap.add_argument("--commit", required=True)
    args = ap.parse_args()
    raw = args.source.read_bytes()
    rules = []
    for line in raw.decode().splitlines():
        line = line.strip()
        if line and not line.startswith("//"):
            rule = line.split()[0]
            rules.append(rule)
            if not rule.isascii():  # also the punycode form, as hosts appear in URLs
                rules.append(".".join(_puny(label) for label in rule.split(".")))
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(
        f"# Public Suffix List, commit {args.commit}, sha256 {hashlib.sha256(raw).hexdigest()}\n"
        "# MPL-2.0, https://mozilla.org/MPL/2.0/ ; generated by scripts/vendor_psl.py\n"
        + "\n".join(rules)
        + "\n"
    )
    notices = NOTICES.read_text()
    block = (
        f"{HEADER}\nLicense: MPL-2.0. Public suffixes, used to find the registrable domain of "
        f"a host.\nCommit {args.commit}\n"
    )
    pattern = re.compile(re.escape(HEADER) + r".*?(?=\n== |\Z)", re.S)
    if pattern.search(notices):
        notices = pattern.sub(block.rstrip("\n"), notices)
    else:
        marker = "\n== Vendored commits =="
        head, sep, tail = notices.partition(marker)
        notices = head.rstrip() + "\n\n" + block + sep + tail
    NOTICES.write_text(notices)
    print(f"wrote {len(rules)} suffixes to {OUT.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
