"""Vendor secret-detection rules from gitleaks and Betterleaks (both MIT) into
src/tainttrap/data/secrets/rules.toml (research R-05, task T021).

Usage: python scripts/vendor_secret_rules.py GITLEAKS_TOML BETTERLEAKS_TOML \
           --gitleaks-commit SHA --betterleaks-commit SHA

- `validate` blocks are dropped (they make network calls).
- Go's mid-pattern `(?i)` is rewritten to a scoped `(?i:...)` group, which Python accepts.
- Every kept regex must compile with Python `re`.
"""

from __future__ import annotations

import argparse
import json
import re
import sys
import tomllib
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "src/tainttrap/data/secrets/rules.toml"
NOTICES = ROOT / "THIRD_PARTY_NOTICES"

BETTERLEAKS_EXTRA = {
    "aws-secret-access-key",
    "gcp-service-account",
    "gcp-application-default-credentials",
    "azure-storage-account-key",
    "gcp-gemini-api",
}
_ENTROPY_FILTER = re.compile(r'^\s*entropy\(finding\["secret"\]\)\s*<=\s*([0-9.]+)\s*$')


def scope_inline_flags(pattern: str) -> str:
    """Rewrite each `(?i)` that is not at the start of the pattern into `(?i:...)`
    spanning to the end of its enclosing group, as Go's RE2 semantics define."""
    out = pattern
    while True:
        idx = _find_midpattern_flag(out)
        if idx < 0:
            return out
        end = _enclosing_group_end(out, idx + 4)
        out = out[:idx] + "(?i:" + out[idx + 4 : end] + ")" + out[end:]


def _find_midpattern_flag(p: str) -> int:
    i, in_class = 0, False
    while i < len(p):
        c = p[i]
        if c == "\\":
            i += 2
            continue
        if in_class:
            in_class = c != "]"
        elif c == "[":
            in_class = True
        elif p.startswith("(?i)", i) and i > 0:
            return i
        i += 1
    return -1


def _enclosing_group_end(p: str, start: int) -> int:
    depth, i, in_class = 0, start, False
    while i < len(p):
        c = p[i]
        if c == "\\":
            i += 2
            continue
        if in_class:
            in_class = c != "]"
        elif c == "[":
            in_class = True
        elif c == "(":
            depth += 1
        elif c == ")":
            if depth == 0:
                return i
            depth -= 1
        i += 1
    return len(p)


def _confidence(rule_id: str, upstream: str | None) -> str:
    if upstream in ("medium", "low"):
        return "medium"
    if "generic" in rule_id:
        return "medium"
    return "high"


def convert(rule: dict, source: str) -> dict | None:
    if "regex" not in rule:  # path-only rules
        return None
    # Go's end-of-text `\z` is `\Z` in Python.
    regex = re.sub(r"(?<!\\)((?:\\\\)*)\\z", r"\1\\Z", scope_inline_flags(rule["regex"]))
    try:
        re.compile(regex)
    except re.error as e:
        print(f"skip {rule['id']}: {e}", file=sys.stderr)
        return None
    out = {
        "id": rule["id"],
        "source": source,
        "regex": regex,
        "keywords": [k.lower() for k in rule.get("keywords", [])],
        "confidence": _confidence(rule["id"], rule.get("confidence")),
    }
    entropy = rule.get("entropy")
    m = _ENTROPY_FILTER.match(rule.get("filter", "") or "")
    if m:
        entropy = float(m.group(1))
    if entropy:
        out["entropy"] = float(entropy)
    if rule.get("secretGroup"):
        out["secret_group"] = int(rule["secretGroup"])
    stopwords: list[str] = []
    for al in rule.get("allowlists", []) or []:
        stopwords.extend(al.get("stopwords", []))
    if stopwords:
        out["stopwords"] = sorted(set(stopwords))
    return out


def _toml_value(v: object) -> str:
    if isinstance(v, bool):
        return "true" if v else "false"
    if isinstance(v, (int, float)):
        return repr(v)
    if isinstance(v, str):
        return json.dumps(v, ensure_ascii=False)  # JSON escapes are valid TOML basic strings
    if isinstance(v, list):
        return "[" + ", ".join(_toml_value(x) for x in v) + "]"
    raise TypeError(type(v))


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("gitleaks")
    ap.add_argument("betterleaks")
    ap.add_argument("--gitleaks-commit", required=True)
    ap.add_argument("--betterleaks-commit", required=True)
    args = ap.parse_args()

    gl = tomllib.loads(Path(args.gitleaks).read_text())
    bl = tomllib.loads(Path(args.betterleaks).read_text())
    rules = [r for r in (convert(x, "gitleaks") for x in gl["rules"]) if r]
    have = {r["id"] for r in rules}
    for x in bl["rules"]:
        if x["id"] in BETTERLEAKS_EXTRA and x["id"] not in have:
            r = convert(x, "betterleaks")
            if r:
                rules.append(r)

    lines = [
        "# Generated by scripts/vendor_secret_rules.py. Do not edit by hand.",
        f"# gitleaks@{args.gitleaks_commit} (MIT), betterleaks@{args.betterleaks_commit} (MIT)",
        "",
    ]
    for r in rules:
        lines.append("[[rules]]")
        lines.extend(f"{k} = {_toml_value(v)}" for k, v in r.items())
        lines.append("")
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text("\n".join(lines))
    tomllib.loads(OUT.read_text())  # round-trip check

    notices = NOTICES.read_text()
    marker = "\n== Vendored commits ==\n"
    notices = notices.split(marker)[0].rstrip() + marker
    notices += f"gitleaks {args.gitleaks_commit}\nbetterleaks {args.betterleaks_commit}\n"
    NOTICES.write_text(notices)
    print(f"wrote {len(rules)} rules to {OUT.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
